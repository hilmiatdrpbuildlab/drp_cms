/**
 * Turns a CMS post into the exact files Publish commits to drp_compro. Pure, so it is unit-tested.
 *
 * In the editor, images point at the CMS (`/api/media/posts/<postId>/<file>`) so the preview works
 * behind login. On publish each referenced image is copied into content/blog/media/<slug>/ and the
 * reference rewritten to `./media/<slug>/<file>`, so the static site never depends on the CMS.
 */
import {
  articleMediaDir,
  articleMediaRef,
  articlePath,
  frontmatterSchema,
  toMarkdownFile,
  type ArticleFrontmatter,
  type ArticleVideo,
  type Category,
  type Lang,
} from "./contract.ts";

/** New articles start with `untitled-<random>` until they get a title; that never goes on the site. */
export const PLACEHOLDER_SLUG_PREFIX = "untitled-";

export const MEDIA_URL_PREFIX = "/api/media/";
export const mediaUrl = (key: string) => `${MEDIA_URL_PREFIX}${key}`;

// posts/<uuid>/<file>; file names are generated by the upload route, so this charset is complete.
const MEDIA_URL_RE = /\/api\/media\/(posts\/[0-9a-f-]{36}\/[A-Za-z0-9._-]+)/g;

export const mediaFileName = (key: string) => key.slice(key.lastIndexOf("/") + 1);

/** Every media key the text refers to, in order of first appearance. */
export function collectMediaKeys(text: string): string[] {
  return [...new Set([...text.matchAll(MEDIA_URL_RE)].map((m) => m[1]))];
}

export function rewriteMediaUrls(text: string, slug: string): string {
  return text.replace(MEDIA_URL_RE, (_, key: string) => articleMediaRef(slug, mediaFileName(key)));
}

export type PostForPublish = {
  title: string;
  slug: string;
  excerpt: string;
  body: string;
  category: Category;
  tags: string[];
  langs: string[];
  authorName: string;
  date: string | null;
  coverKey: string | null;
  coverAlt: string;
  video: ArticleVideo | null;
  /** Slug of the last publish, if any, so a rename removes the old file. */
  publishedSlug: string | null;
};

export type PublishPlan = {
  frontmatter: ArticleFrontmatter;
  markdownPath: string;
  markdown: string;
  /** media key in the bucket -> path in drp_compro */
  media: { key: string; path: string }[];
  /** Directory whose other files should be removed (images no longer used). */
  mediaDir: string;
  /** Left over from a previous slug: delete the old .md and its media dir. */
  oldSlug: string | null;
};

export type PlanResult = { ok: true; plan: PublishPlan } | { ok: false; errors: string[] };

export function planPublish(post: PostForPublish, today: string): PlanResult {
  const date = post.date ?? today;
  const keys = new Set(collectMediaKeys(post.body));
  if (post.coverKey) keys.add(post.coverKey);
  const videoPosterKey = post.video?.poster ? collectMediaKeys(post.video.poster)[0] : undefined;
  if (videoPosterKey) keys.add(videoPosterKey);

  const candidate = {
    title: post.title,
    slug: post.slug,
    date,
    updated: post.publishedSlug ? today : undefined,
    author: post.authorName,
    category: post.category,
    tags: post.tags,
    // English is the source the site translates from, so it is always published.
    langs: ["en", ...post.langs.filter((l) => l !== "en")] as Lang[],
    excerpt: post.excerpt,
    cover: post.coverKey ? { src: articleMediaRef(post.slug, mediaFileName(post.coverKey)), alt: post.coverAlt } : undefined,
    video: post.video
      ? { ...post.video, poster: post.video.poster ? rewriteMediaUrls(post.video.poster, post.slug) : undefined }
      : undefined,
    draft: false,
  };

  const parsed = frontmatterSchema.safeParse(candidate);
  const errors = parsed.success ? [] : parsed.error.issues.map((i) => `${i.path.join(".") || "article"}: ${i.message}`);
  if (post.body.trim().length < 50) errors.push("body: write at least a paragraph before publishing");
  if (post.slug.startsWith(PLACEHOLDER_SLUG_PREFIX)) errors.push("slug: still the placeholder web address. Give the article a title, or type a web address");
  if (!parsed.success || errors.length) return { ok: false, errors };

  const body = rewriteMediaUrls(post.body, post.slug);
  return {
    ok: true,
    plan: {
      frontmatter: parsed.data,
      markdownPath: articlePath(post.slug),
      markdown: toMarkdownFile(parsed.data, body),
      media: [...keys].map((key) => ({ key, path: `${articleMediaDir(post.slug)}${mediaFileName(key)}` })),
      mediaDir: articleMediaDir(post.slug),
      oldSlug: post.publishedSlug && post.publishedSlug !== post.slug ? post.publishedSlug : null,
    },
  };
}
